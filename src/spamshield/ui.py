"""Shared Streamlit helpers: cached artifact loading and small UI utilities.

Model artifacts are cached for the whole session with ``st.cache_resource`` and metrics
with ``st.cache_data``, so opening a page never retrains anything.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd
import streamlit as st

from .constants import (
    FIGURES_DIR,
    METRICS_CSV_PATH,
    METRICS_JSON_PATH,
    MODELS_DIR,
)
from .data import clean_dataset, load_dataset
from .models import MODEL_NAMES
from .predict import TRAIN_COMMAND, available_models, load_pipeline


@st.cache_resource(show_spinner=False)
def get_pipeline(key: str) -> tuple[Any, dict[str, Any]]:
    """Load and cache one fitted pipeline (kept in memory for the whole session)."""
    return load_pipeline(key)


@st.cache_data(show_spinner=False)
def get_metrics_frame() -> pd.DataFrame:
    """Load the saved comparison table."""
    return pd.read_csv(METRICS_CSV_PATH)


@st.cache_data(show_spinner=False)
def get_metrics_payload() -> dict[str, Any]:
    """Load the saved evaluation JSON (selection, notes and per-model reports)."""
    return json.loads(Path(METRICS_JSON_PATH).read_text(encoding="utf-8"))


@st.cache_data(show_spinner="Loading the SMS dataset ...")
def get_dataset() -> tuple[pd.DataFrame, dict[str, Any]]:
    """Load and clean the dataset once, then serve it from cache."""
    frame = load_dataset()
    cleaned, report = clean_dataset(frame)
    return cleaned, report.as_dict()


def require_trained_models() -> list[str]:
    """Return the trained model keys, or stop the page with instructions."""
    keys = available_models()
    if not keys:
        st.error("No trained models were found in `artifacts/models`.")
        st.write("Train the six models first:")
        st.code(TRAIN_COMMAND, language="bash")
        st.stop()
    return keys


def require_metrics() -> None:
    """Stop the page with instructions when evaluation results are missing."""
    if not (METRICS_CSV_PATH.exists() and METRICS_JSON_PATH.exists()):
        st.error("No evaluation results were found in `artifacts/metrics`.")
        st.write("Generate them first:")
        st.code(TRAIN_COMMAND, language="bash")
        st.stop()


def model_name(key: str) -> str:
    """Return the display name of a model."""
    return MODEL_NAMES.get(key, key)


def show_figure(filename: str, caption: str | None = None) -> None:
    """Display a figure generated by the evaluation pipeline, if it exists."""
    path = Path(FIGURES_DIR) / filename
    if path.exists():
        st.image(str(path), caption=caption, width="stretch")
    else:
        st.caption(f"Figure `{filename}` has not been generated yet. Run `{TRAIN_COMMAND}`.")


def models_directory() -> Path:
    return Path(MODELS_DIR)
